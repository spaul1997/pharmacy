const statusOptions = ["Active", "Inactive", "Draft"];
const isNonSupplierCategory = (row) => row.type !== "Supplier";
const isRootCategory = (row) => {
  const parent = String(row.parent || "").trim();
  return !parent || parent === "-" || parent === "\u2014";
};
const isNonSupplierRootCategory = (row) => isNonSupplierCategory(row) && isRootCategory(row);
const isNonSupplierSubCategory = (row, values) => isNonSupplierCategory(row) && Boolean(values.category) && row.parent === values.category;

function simplePharmacyMaster({
  label,
  singular = label,
  icon = "Tags",
  codeLabel,
  nameLabel,
  description,
  rows = [],
  extraFields = [],
  columns = [],
  autoGeneratedCode = true,
  includeName = true,
  includeDescription = true,
  searchKeys,
  deriveRow,
  draftRequiredKeys,
  draftRequiredMessage,
  uniqueTogether,
  uniqueTogetherMessage,
  compactForm = false,
  compactDescriptionColumns,
}) {
  const compactColumns = compactForm
    ? (Number.isInteger(compactForm) ? compactForm : 4)
    : undefined;

  return {
    label,
    singular,
    icon,
    description,
    statLabel: `Total ${label}`,
    autoGeneratedCode,
    draftRequiredKeys,
    draftRequiredMessage,
    uniqueTogether,
    uniqueTogetherMessage,
    list: {
      subtitle: description,
      searchPlaceholder: `Search ${label.toLowerCase()}...`,
      searchKeys: searchKeys || ["code", ...(includeName ? ["name"] : [])],
      deriveRow,
      filters: [{ key: "status", label: "Status", options: ["Active", "Inactive", "Draft"] }],
      summary: [
        { label: `Total ${label}`, tone: "primary", compute: (items) => items.length },
        { label: "Active", tone: "success", compute: (items) => items.filter((item) => item.status === "Active").length },
        { label: "Inactive", tone: "muted", compute: (items) => items.filter((item) => item.status === "Inactive").length },
        { label: "Draft", tone: "accent", compute: (items) => items.filter((item) => item.status === "Draft").length },
      ],
      columns: [
        { key: "code", label: codeLabel || `${singular} Code`, mono: true },
        ...(includeName ? [{ key: "name", label: nameLabel || singular }] : []),
        ...columns,
        { key: "status", label: "Status", badge: true },
      ],
      rows,
    },
    form: {
      tabs: [{
        key: "details",
        label: `${singular} Details`,
        columns: compactColumns,
        compact: compactForm,
        fields: [
          ...(!autoGeneratedCode ? [{ key: "code", label: codeLabel || `${singular} Code`, type: "text", required: true }] : []),
          ...(includeName ? [{ key: "name", label: nameLabel || singular, type: "text", required: true }] : []),
          ...extraFields,
          ...(!compactForm && includeDescription ? [{ key: "description", label: "Description", type: "textarea", span: "full" }] : []),
          { key: "status", label: "Status", type: "select", options: statusOptions },
          ...(compactForm && includeDescription ? [{
            key: "description",
            label: "Description",
            type: "textarea",
            spanColumns: compactDescriptionColumns || (compactColumns === 4 ? 3 : compactColumns),
            rows: 2,
          }] : []),
        ],
      }],
    },
  };
}

